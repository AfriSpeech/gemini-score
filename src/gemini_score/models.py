"""Data structures and results for GeminiScore."""

from __future__ import annotations

import json
from dataclasses import asdict, dataclass
from typing import Any, Dict, List, Optional, Sequence, Union


@dataclass
class GeminiScoreResult:
    """Evaluation result returned by GeminiScore.

    Attributes
    ----------
    score: float
        The overall system-level average score across all samples.
    scores: List[float]
        Per-sample semantic similarity scores.
    predictions: List[str]
        Input African language prediction strings evaluated.
    references: List[Union[str, List[str]]]
        Reference English sentences evaluated against.
    translations: List[str]
        Back-translations to English generated by Gemini.
    languages: List[str]
        Resolved African language names for each sample.
    scale: str
        Scoring scale ('percent', 'unit', or 'raw').
    model: str
        Gemini model identifier used for translation.
    similarity_model: str
        Model2Vec static embedding model used for similarity.
    """

    score: float
    scores: List[float]
    predictions: List[str]
    references: List[Union[str, List[str]]]
    translations: List[str]
    languages: List[str]
    scale: str = "percent"
    model: str = "gemini-2.5-flash"
    similarity_model: str = "minishlab/M2V_base_output"

    def __len__(self) -> int:
        return len(self.scores)

    def __getitem__(self, idx: int) -> Dict[str, Any]:
        return {
            "prediction": self.predictions[idx],
            "reference": self.references[idx],
            "translation": self.translations[idx],
            "score": self.scores[idx],
            "language": self.languages[idx],
        }

    def __repr__(self) -> str:
        return (
            f"GeminiScoreResult(score={self.score:.2f}, "
            f"num_samples={len(self.scores)}, "
            f"scale='{self.scale}', "
            f"model='{self.model}', "
            f"similarity_model='{self.similarity_model}')"
        )

    def to_dict(self) -> Dict[str, Any]:
        """Converts the result to a dictionary."""
        return {
            "score": self.score,
            "scores": self.scores,
            "predictions": self.predictions,
            "references": self.references,
            "translations": self.translations,
            "languages": self.languages,
            "scale": self.scale,
            "model": self.model,
            "similarity_model": self.similarity_model,
        }

    def to_json(self, indent: int = 2) -> str:
        """Serializes the result dictionary to a JSON formatted string."""
        return json.dumps(self.to_dict(), indent=indent, ensure_ascii=False)

    def to_dataframe(self) -> Any:
        """Converts sample-level results into a pandas DataFrame."""
        try:
            import pandas as pd
        except ImportError:
            raise ImportError(
                "pandas is required to convert results to a DataFrame. "
                "Install it with `pip install pandas`."
            )

        data = {
            "prediction": self.predictions,
            "reference": self.references,
            "translation": self.translations,
            "score": self.scores,
            "language": self.languages,
        }
        return pd.DataFrame(data)

    def summary(self) -> str:
        """Returns a formatted textual summary of the evaluation."""
        if not self.scores:
            return "GeminiScore: 0 samples evaluated."

        import numpy as np

        arr = np.array(self.scores)
        unit_sym = "%" if self.scale == "percent" else ""
        return (
            f"=== GeminiScore Evaluation Summary ===\n"
            f"System Score (Mean) : {self.score:.2f}{unit_sym}\n"
            f"Median              : {float(np.median(arr)):.2f}{unit_sym}\n"
            f"Std Dev             : {float(np.std(arr)):.2f}\n"
            f"Min                 : {float(np.min(arr)):.2f}{unit_sym}\n"
            f"Max                 : {float(np.max(arr)):.2f}{unit_sym}\n"
            f"Samples Evaluated   : {len(self.scores)}\n"
            f"Gemini Model        : {self.model}\n"
            f"Similarity Model    : {self.similarity_model}\n"
            f"Scale               : {self.scale}\n"
            f"======================================"
        )
